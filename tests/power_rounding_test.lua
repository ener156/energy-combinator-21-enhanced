-- New map-wide rounding selectors; existing default modes must not regress.
local function mode_check(name, input, mode, expected)
    local actual = rounding.round_signal(input, mode)
    assert(actual == expected,
        string.format("%s: input=%.17g; mode=%s; expected=%d; actual=%d",
            name, input, mode, expected, actual))
    print("ROUNDING_MODE_PASS|" .. name)
end

